#!/usr/bin/env python3
"""Create a private production environment file with fresh, distinct secrets."""

from __future__ import annotations

import argparse
import ipaddress
import secrets
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vps-ip", required=True, help="Public IPv4 address of the VPS")
    parser.add_argument("--frontend-origin", required=True, help="Exact HTTPS Vercel origin, e.g. https://veilbench-demo.vercel.app")
    parser.add_argument("--dns-suffix", choices=("sslip.io", "nip.io"), default="sslip.io", help="Temporary IP-based DNS suffix (default: sslip.io)")
    parser.add_argument("--output", default=str(ROOT / ".env.production"), help="Output path (default: .env.production)")
    parser.add_argument("--force", action="store_true", help="Replace an existing output file")
    args = parser.parse_args()

    ip = ipaddress.ip_address(args.vps_ip)
    if not isinstance(ip, ipaddress.IPv4Address) or not ip.is_global:
        parser.error("--vps-ip must be a globally routable public IPv4 address")
    frontend = urlsplit(args.frontend_origin.rstrip("/"))
    if (
        frontend.scheme != "https"
        or not frontend.netloc
        or frontend.username
        or frontend.password
        or frontend.path
        or frontend.query
        or frontend.fragment
        or frontend.hostname in {"localhost", "127.0.0.1", "::1"}
    ):
        parser.error("--frontend-origin must be a public HTTPS origin without credentials, path, query, or fragment")

    output = Path(args.output).expanduser().resolve()
    if output.exists() and not args.force:
        parser.error(f"{output} already exists; use --force only if you intend to rotate every generated secret")

    host_base = f"{ip}.{args.dns_suffix}"
    api_host = f"api.{host_base}"
    party_hosts = [f"party{party_id}.{host_base}" for party_id in range(3)]
    db_password = secrets.token_urlsafe(32)
    values = {
        "ENVIRONMENT": "production",
        "DEBUG": "false",
        "DATABASE_AUTO_CREATE": "false",
        "POSTGRES_USER": "veilbench_user",
        "POSTGRES_PASSWORD": db_password,
        "POSTGRES_DB": "veilbench_db",
        "DATABASE_URL": f"postgresql+asyncpg://veilbench_user:{db_password}@veilbench-db:5432/veilbench_db",
        "COORDINATOR_ADMIN_TOKEN": secrets.token_urlsafe(48),
        "MPC_FOUNDER_TOKEN_SECRET_0": secrets.token_urlsafe(48),
        "MPC_FOUNDER_TOKEN_SECRET_1": secrets.token_urlsafe(48),
        "MPC_FOUNDER_TOKEN_SECRET_2": secrets.token_urlsafe(48),
        "MPC_NODE0_TOKEN": secrets.token_urlsafe(48),
        "MPC_NODE1_TOKEN": secrets.token_urlsafe(48),
        "MPC_NODE2_TOKEN": secrets.token_urlsafe(48),
        "FRONTEND_PUBLIC_URL": args.frontend_origin.rstrip("/"),
        "ALLOWED_ORIGINS": args.frontend_origin.rstrip("/"),
        "MPC_PARTY_ALLOWED_ORIGINS": args.frontend_origin.rstrip("/"),
        "MPC_PARTY_PUBLIC_URLS": ",".join(f"https://{host}" for host in party_hosts),
        "VEILBENCH_API_HOST": api_host,
        "VEILBENCH_PARTY0_HOST": party_hosts[0],
        "VEILBENCH_PARTY1_HOST": party_hosts[1],
        "VEILBENCH_PARTY2_HOST": party_hosts[2],
        "NEXT_PUBLIC_API_URL": f"https://{api_host}",
        "NEXT_PUBLIC_PARTY_0_URL": f"https://{party_hosts[0]}",
        "NEXT_PUBLIC_PARTY_1_URL": f"https://{party_hosts[1]}",
        "NEXT_PUBLIC_PARTY_2_URL": f"https://{party_hosts[2]}",
        "MPC_REQUIRE_TLS": "true",
        "MPC_REQUIRE_CLIENT_CERT": "true",
        "MPC_PARTIES_COUNT": "3",
        "MPC_THRESHOLD": "1",
        "MPC_TIMEOUT_SECONDS": "30",
        "SESSION_TTL_SECONDS": "1800",
        "MPC_CA_CERT_PATH": "/app/certs/ca/ca.crt",
        "MPC_CLIENT_CERT_PATH": "/app/certs/coordinator/coordinator.crt",
        "MPC_CLIENT_KEY_PATH": "/app/certs/coordinator/coordinator.key",
    }
    lines = [
        "# Generated by scripts/generate_production_env.py. Keep this file private.",
        "# Never commit this file or paste its contents into support chats.",
    ]
    lines.extend(f"{key}={value}" for key, value in values.items())
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        output.chmod(0o600)
    except OSError:
        pass

    print(f"Created {output}")
    print("Public API:", values["NEXT_PUBLIC_API_URL"])
    for party_id in range(3):
        print(f"Party {party_id}:", values[f"NEXT_PUBLIC_PARTY_{party_id}_URL"])
    print("Frontend origin:", values["FRONTEND_PUBLIC_URL"])
    print("Generated seven distinct high-entropy application secrets and a URL-safe database password.")
    print(f"The {args.dns_suffix} names are temporary DNS names; public ACME issuance depends on DNS, ports 80/443, and CA policy/rate limits.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
